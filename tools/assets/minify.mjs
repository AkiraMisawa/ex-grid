// Minifies the JavaScript and CSS each package ships (ADR-0123). The source a contributor edits is
// src/<Package>/Assets/<name>; what ships is src/<Package>/wwwroot/<name without extension>.min.<ext>
// and its source map, which carries the source itself so a browser's debugger shows it. Both are
// committed, so a build needs no Node: run this after editing a source, and commit what it writes.
//
// Each minified file opens with the SHA-256 of its source, line endings read as LF so a Windows
// checkout hashes the same text. ShippedAssetTests compares it with the source, so a source edited
// without running this fails layer 2 by name.
//
//     cd tools/assets && npm ci && npm run minify
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '../..');

/** Every package's sources, in a fixed order so the output never depends on the file system. */
export const sources = [
    'src/ExGrid/Assets/ex-grid.js',
    'src/ExGrid/Assets/ex-grid.css',
    'src/ExGrid.MudBlazor/Assets/mud-ex-grid.css',
    'src/ExPivot/Assets/ex-pivot.css',
    'src/ExPivot.MudBlazor/Assets/mud-ex-pivot.css',
    'src/ExSheet/Assets/ex-sheet.css',
    'src/ExSheet.MudBlazor/Assets/mud-ex-sheet.css',
];

const hashOf = (text) => createHash('sha256').update(text.replace(/\r\n/g, '\n'), 'utf8').digest('hex');

for (const source of sources) {
    const input = path.join(repo, source);
    const name = path.basename(source);
    const extension = path.extname(name);
    const minified = `${path.basename(name, extension)}.min${extension}`;
    const outfile = path.join(path.dirname(input), '..', 'wwwroot', minified);
    const text = fs.readFileSync(input, 'utf8');
    const banner = `/*! ${name} sha256:${hashOf(text)} - generated by tools/assets/minify.mjs (ADR-0123): edit Assets/${name} and run it again */`;

    await build({
        entryPoints: [input],
        outfile,
        bundle: false,
        minify: true,
        format: extension === '.js' ? 'esm' : undefined,
        target: 'esnext',
        charset: 'utf8',
        legalComments: 'none',
        banner: { [extension.slice(1)]: banner },
        sourcemap: 'linked',
        sourcesContent: true,
        logLevel: 'warning',
    });

    // The map names the source as the package's own file, not a path of this checkout.
    const mapFile = `${outfile}.map`;
    const map = JSON.parse(fs.readFileSync(mapFile, 'utf8'));
    map.sources = [name];
    fs.writeFileSync(mapFile, `${JSON.stringify(map)}\n`);

    const before = fs.statSync(input).size;
    const after = fs.statSync(outfile).size;
    console.log(`${source} -> ${path.relative(repo, outfile)}: ${before} -> ${after} bytes`);
}
