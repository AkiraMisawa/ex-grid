let undeclared: ReadonlySet<string> | undefined;

/** Whether Excel has a worksheet function of this name that ExSheet does not declare, the name read without regard to case. */
export function isUndeclaredExcelFunction(name: string): boolean {
    undeclared ??= new Set(excelFunctionNames.map(ignoreCaseKey));
    return undeclared.has(ignoreCaseKey(name));
}
