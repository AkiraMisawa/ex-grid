// Builds the script Blazor's ExGrid imports (ADR-0350 sections 7 and 9): the bridge and the Script Core it
// mounts, read from their sources and bundled into one minified ES module with its source map, which the ExGrid
// NuGet package ships. Nothing here is published to npm.
//
// Each package asks for the files it was built with (ADR-0123): the module answers `stamp()`, the SHA-256 of
// every source it was bundled from, and the component compares it with the stamp it was built with before it
// attaches anything. Beside the module this writes `ex-grid-core.stamp.json`: the stamp, and the version the
// module's address carries, the first twelve hex digits of the shipped file's own SHA-256. Given --cs, it also
// writes both as the C# constants the ExGrid build compiles (`ScriptCoreAsset`).
//
// Run from src/npm/blazor, as its `npm run build`, or by the ExGrid build:
//
//   node ../scripts/build-blazor.mjs [--out <directory>] [--stamp <file>] [--cs <file>]
//
// The module and its map go to --out, dist/ unless given; the stamp to --stamp, beside them unless given. The ExGrid
// build puts the stamp and the constants outside what the package serves.
import { build } from 'esbuild';
import { createHash } from 'node:crypto';
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const here = process.cwd();
const workspace = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const at = process.argv.indexOf('--out');
const out = path.resolve(at < 0 ? path.join(here, 'dist') : process.argv[at + 1]);
const name = 'ex-grid-core';
const stampAt = process.argv.indexOf('--stamp');
const stampFile = path.resolve(stampAt < 0 ? path.join(out, `${name}.stamp.json`) : process.argv[stampAt + 1]);
const csAt = process.argv.indexOf('--cs');
const csFile = csAt < 0 ? null : path.resolve(process.argv[csAt + 1]);

/** The packages are read from their sources, so the bundle is the checkout's code and needs no build of them. */
const alias = {
    '@ex-grid/core': path.join(workspace, 'core/src/index.ts'),
    '@ex-grid/data': path.join(workspace, 'data/src/index.ts'),
};

const hashOf = (text) => createHash('sha256').update(text.replace(/\r\n/g, '\n'), 'utf8').digest('hex');

const settings = {
    entryPoints: [path.join(here, 'src/index.ts')],
    bundle: true,
    format: 'esm',
    platform: 'browser',
    target: 'es2022',
    alias,
    legalComments: 'none',
    logLevel: 'warning',
};

// First what the bundle reads, so its stamp names every source, in an order that never depends on the file
// system, by path relative to the workspace and content.
const probe = await build({ ...settings, write: false, metafile: true, define: { EX_SOURCE_SHA256: '""' } });
const inputs = Object.keys(probe.metafile.inputs)
    .map(input => path.resolve(process.cwd(), input))
    .map(file => [path.relative(workspace, file).split(path.sep).join('/'), file])
    .toSorted(([a], [b]) => (a < b ? -1 : a > b ? 1 : 0));
const stamp = hashOf(inputs.map(([relative, file]) => `${relative}\n${fs.readFileSync(file, 'utf8')}`).join('\n'));

fs.mkdirSync(out, { recursive: true });
const outfile = path.join(out, `${name}.min.js`);
await build({
    ...settings,
    outfile,
    minify: true,
    charset: 'utf8',
    sourcemap: 'linked',
    sourcesContent: true,
    banner: { js: `/*! ${name}.js sha256:${stamp} - built by src/npm/scripts/build-blazor.mjs (ADR-0123) from the Script Core's sources */` },
    define: { EX_SOURCE_SHA256: JSON.stringify(stamp) },
});

// The map names each source by its place in the workspace, not by a path of this checkout.
const mapFile = `${outfile}.map`;
const map = JSON.parse(fs.readFileSync(mapFile, 'utf8'));
map.sources = map.sources.map(source => path.relative(workspace, path.resolve(path.dirname(mapFile), source)).split(path.sep).join('/'));
fs.writeFileSync(mapFile, `${JSON.stringify(map)}\n`);

const shipped = fs.readFileSync(outfile, 'utf8');
if (!shipped.includes(`"${stamp}"`)) throw new Error(`${outfile} does not answer its stamp; see ADR-0123`);
const version = hashOf(shipped).slice(0, 12);
fs.mkdirSync(path.dirname(stampFile), { recursive: true });
fs.writeFileSync(stampFile, `${JSON.stringify({ stamp, version })}\n`);
if (csFile !== null) {
    fs.mkdirSync(path.dirname(csFile), { recursive: true });
    fs.writeFileSync(csFile, [
        '// <auto-generated>Written by src/npm/scripts/build-blazor.mjs as ExGrid builds (ADR-0123, ADR-0350 section 7).</auto-generated>',
        'namespace ExGrid.Script;',
        '',
        '/// <summary>The Script Core\'s module as this build of ExGrid ships it.</summary>',
        'internal static class ScriptCoreAsset',
        '{',
        '    /// <summary>The first 12 hex digits of the SHA-256 of the shipped module: the version its address carries.</summary>',
        `    internal const string Version = "${version}";`,
        '',
        '    /// <summary>The SHA-256 of every source the module was bundled from, which it answers: its stamp.</summary>',
        `    internal const string Stamp = "${stamp}";`,
        '}',
        '',
    ].join('\n'));
}
console.log(`${path.relative(process.cwd(), outfile)}: ${shipped.length} bytes from ${inputs.length} sources, version ${version}`);
